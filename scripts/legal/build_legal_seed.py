#!/usr/bin/env python3
"""Builds the legal-documents seed from the binding source file, verbatim (no text is shortened or edited).

Usage: python3 scripts/legal/build_legal_seed.py docs/legal/LINKUP_legal_package_2026-11-10.md
Writes supabase/seed/legal_documents_v1_draft.sql (inserts DRAFTS only; publication is a separate, approved step).
"""
import hashlib, re, sys, pathlib

KEYS = [  # section number → (doc_key, audience, sort)
    ("terms", "all", 10), ("store-terms", "store", 20), ("creator-terms", "creator", 30), ("privacy", "notice", 40),
    ("commissions", "store", 50), ("founding-partners", "none", 60), ("cookies", "none", 70), ("interface-notices", "none", 80),
]
VERSION = 1

def parse(text):
    parts = re.split(r"^## (\d)\. (.+)$", text, flags=re.M)
    docs = []
    for i in range(1, len(parts), 3):
        n, title, block = int(parts[i]), parts[i + 1].strip(), parts[i + 2]
        if n < 1 or n > 8: continue
        block = block.split("\n## Appendix")[0]
        he_title, en_title = [t.strip() for t in title.split("|", 1)]
        if "**English - " in block:
            he, en = block.split("**English - ", 1)
            he_body, en_body = he.strip(), ("**English - " + en).strip()
        else:  # section 8 is bilingual item by item: both language pages carry the full text verbatim
            he_body = en_body = block.strip()
        docs.append((n, he_title, en_title, he_body, en_body))
    assert [d[0] for d in docs] == list(range(1, 9)), "expected sections 1..8"
    return docs

def dq(s, tag="LEGAL"):
    assert f"${tag}$" not in s
    return f"${tag}${s}${tag}$"

def main(src):
    text = pathlib.Path(src).read_text(encoding="utf-8")
    sha = hashlib.sha256(text.encode()).hexdigest()
    out = ["-- GENERATED by scripts/legal/build_legal_seed.py from docs/legal/LINKUP_legal_package_2026-11-10.md",
           f"-- source sha256: {sha}",
           "-- Inserts version 1 of the eight documents (he + en) as DRAFTS. Nothing is published by this file.",
           "-- Publish only after Israeli counsel and CPA approval:  select public.publish_legal_version('<key>', 1, <effective_from>);",
           "begin;"]
    for (n, he_t, en_t, he_b, en_b), (key, aud, sort) in zip(parse(text), KEYS):
        for loc, t, b in (("he", he_t, he_b), ("en", en_t, en_b)):
            out.append("insert into public.legal_documents(doc_key, locale, version, title, body, audience, sort_order, status)\n"
                       f"values ('{key}', '{loc}', {VERSION}, {dq(t, 'T')}, {dq(b)}, '{aud}', {sort}, 'draft')\n"
                       "on conflict (doc_key, locale, version) do nothing;")
    out.append("commit;")
    dst = pathlib.Path(__file__).resolve().parents[2] / "supabase/seed/legal_documents_v1_draft.sql"
    dst.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {dst} ({len(KEYS) * 2} rows, source sha256 {sha[:12]}…)")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "docs/legal/LINKUP_legal_package_2026-11-10.md")
